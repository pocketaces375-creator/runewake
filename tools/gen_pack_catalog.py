#!/usr/bin/env python3
"""FABLE-061: write the card list the pack server rolls from.

  python3 tools/gen_pack_catalog.py            → supabase/pack_catalog.sql
  python3 tools/gen_pack_catalog.py --seed     → also supabase/card_discoveries_seed.sql

pack_catalog.sql   every card with its rarity; Lost Relics, tokens and cards marked "pack": false
                   (tower-only) are excluded. Paste into the Supabase SQL editor after packs.sql, and
                   again whenever cards are added or a rarity changes. Idempotent.
card_discoveries_seed.sql
                   OPTIONAL, run once: counts every card that is in the game today as discovered on the
                   day it was added (from git history), so cards players have been finding since launch
                   are not held back a further 90 days from the day packs ship. Never overwrites a real
                   discovery (on conflict do nothing).
"""
import json
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CARDS = REPO / "client" / "content" / "cards"
RELICS = REPO / "client" / "content" / "relics" / "relic_defs.json"
RARITIES = {"COMMON", "UNCOMMON", "RARE", "RELIC"}


def load_cards():
    out = {}
    for f in sorted(CARDS.glob("*.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        for c in (d.get("cards") if isinstance(d, dict) else d) or []:
            if isinstance(c, dict) and c.get("id"):
                out[c["id"]] = c
    return out


def lost_relic_ids():
    if not RELICS.exists():
        return set()
    d = json.loads(RELICS.read_text(encoding="utf-8"))
    return {r["card_id"] for r in d.get("relics", []) if r.get("card_id")}


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def catalog_sql(cards, relics):
    rows, excluded = [], 0
    for cid, c in sorted(cards.items()):
        rarity = str(c.get("rarity", "COMMON")).upper()
        if rarity not in RARITIES:
            continue
        ex = c.get("type") == "TOKEN" or cid in relics or c.get("pack") is False
        excluded += ex
        rows.append(f"  ({q(cid)}, {q(rarity)}, {'true' if ex else 'false'})")
    head = ("-- GENERATED by tools/gen_pack_catalog.py — do not edit by hand. FABLE-061.\n"
            f"-- {len(rows)} cards, {excluded} never in packs (Lost Relics, tokens, tower-only).\n"
            "-- Run after packs.sql, and again whenever cards change. Idempotent.\n")
    return (head + "insert into public.pack_catalog (card_id, rarity, excluded) values\n" + ",\n".join(rows) +
            "\non conflict (card_id) do update set rarity = excluded.rarity, excluded = excluded.excluded, updated_at = now();\n")


def first_seen_dates(ids):
    """The date each card id first appeared in client/content/cards, walking the git history oldest first."""
    log = subprocess.run(["git", "-C", str(REPO), "log", "--reverse", "--format=%H %cs", "--", "client/content/cards"],
                         capture_output=True, text=True, check=True).stdout.split("\n")
    seen = {}
    for line in log:
        if not line.strip():
            continue
        sha, day = line.split()
        files = subprocess.run(["git", "-C", str(REPO), "ls-tree", "--name-only", sha, "client/content/cards/"],
                               capture_output=True, text=True).stdout.split()
        for path in files:
            if not path.endswith(".json"):
                continue
            blob = subprocess.run(["git", "-C", str(REPO), "show", f"{sha}:{path}"], capture_output=True, text=True).stdout
            try:
                d = json.loads(blob)
            except ValueError:
                continue
            for c in (d.get("cards") if isinstance(d, dict) else d) or []:
                if isinstance(c, dict) and c.get("id") in ids and c["id"] not in seen:
                    seen[c["id"]] = day
        if len(seen) == len(ids):
            break
    return seen


def seed_sql(cards, relics):
    ids = {cid for cid, c in cards.items() if c.get("type") != "TOKEN" and cid not in relics and c.get("pack") is not False}
    dates = first_seen_dates(ids)
    rows = [f"  ({q(cid)}, 'seed', {q(day + ' 00:00:00+00')})" for cid, day in sorted(dates.items())]
    head = ("-- GENERATED by tools/gen_pack_catalog.py --seed. FABLE-061. OPTIONAL, run once.\n"
            "-- Every card already in the game counts as discovered on the day it was added, so packs\n"
            "-- start with the oldest cards instead of waiting 90 days from launch. Real discoveries win.\n")
    return head + ("insert into public.card_discoveries (card_id, source, discovered_at) values\n" + ",\n".join(rows) +
                   "\non conflict (card_id) do nothing;\n"), dates


def main():
    cards, relics = load_cards(), lost_relic_ids()
    (REPO / "supabase" / "pack_catalog.sql").write_text(catalog_sql(cards, relics), encoding="utf-8")
    print(f"supabase/pack_catalog.sql: {len(cards)} cards")
    if "--seed" in sys.argv:
        text, dates = seed_sql(cards, relics)
        (REPO / "supabase" / "card_discoveries_seed.sql").write_text(text, encoding="utf-8")
        by_day = {}
        for d in dates.values():
            by_day[d] = by_day.get(d, 0) + 1
        print(f"supabase/card_discoveries_seed.sql: {len(dates)} cards — " +
              ", ".join(f"{n} on {d}" for d, n in sorted(by_day.items())))


if __name__ == "__main__":
    main()
