using System.Collections.Generic;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace Runewake.Engine.Cards;

/// <summary>
/// FABLE-068: every class begins in its own land. A start zone dresses the first region
/// (<see cref="StartZoneSet.BaseRegion"/>, region_01) for one class — its name, strata, board skin,
/// where each node sits on the map plate, and which encounter stands on each node — while keeping the
/// region's node ids and unlock graph. Saves, the guided first duel, the campaign loop and the region
/// chain (r1_n12 → region_02) therefore work exactly as before; only what the player meets changes.
/// Content: content/start_zones.json (generated by tools/gen_start_zones.py).
/// </summary>
public sealed class StartZone
{
    [JsonPropertyName("name")] public string Name { get; set; } = "";
    [JsonPropertyName("strata")] public string Strata { get; set; } = "";
    [JsonPropertyName("strata2")] public string? Strata2 { get; set; }
    [JsonPropertyName("board_skin")] public string? BoardSkin { get; set; }
    /// <summary>Node id → [x, y] on the map plate.</summary>
    [JsonPropertyName("positions")] public Dictionary<string, int[]> Positions { get; set; } = new();
    /// <summary>Node id → encounter id.</summary>
    [JsonPropertyName("encounters")] public Dictionary<string, string> Encounters { get; set; } = new();
}

public sealed class StartZoneSet
{
    [JsonPropertyName("base_region")] public string BaseRegion { get; set; } = "region_01";
    /// <summary>Class id → its zone.</summary>
    [JsonPropertyName("zones")] public Dictionary<string, StartZone> Zones { get; set; } = new();

    public static StartZoneSet Parse(string json) =>
        string.IsNullOrWhiteSpace(json) ? new StartZoneSet() : JsonSerializer.Deserialize<StartZoneSet>(json) ?? new StartZoneSet();

    /// <summary>The zone for <paramref name="classId"/>, or null (unknown class: the plain region).</summary>
    public StartZone? For(string? classId) =>
        !string.IsNullOrEmpty(classId) && Zones.TryGetValue(classId!.ToLowerInvariant(), out var z) ? z : null;

    /// <summary>
    /// Dress <paramref name="region"/> for <paramref name="classId"/> in place and return it. Anything that
    /// is not the base region, or a class without a zone, comes back untouched. Node ids, types, links and
    /// unlocks never change; an encounter id the zone does not know stays as authored.
    /// </summary>
    public MapRegion Apply(MapRegion region, string? classId)
    {
        if (region == null || region.Id != BaseRegion) return region!;
        var z = For(classId);
        if (z == null) return region;
        if (!string.IsNullOrEmpty(z.Name)) region.Name = z.Name;
        if (!string.IsNullOrEmpty(z.Strata)) region.Strata = z.Strata;
        if (z.Strata2 != null) region.Strata2 = z.Strata2;
        if (!string.IsNullOrEmpty(z.BoardSkin)) region.BoardSkin = z.BoardSkin;
        foreach (var node in region.Nodes)
        {
            if (z.Positions.TryGetValue(node.Id, out var p) && p is { Length: 2 }) node.Position = new[] { p[0], p[1] };
            if (node.Encounter != null && z.Encounters.TryGetValue(node.Id, out var enc) && !string.IsNullOrEmpty(enc)) node.Encounter = enc;
        }
        return region;
    }
}
